export function randomVariation(p: Personality): Personality {
  const vary = (v: number, range: number) =>
    Math.max(0, Math.min(1, v + (Math.random() - 0.5) * range));
  return {
    ...p,
    curiosity: vary(p.curiosity, 0.2),
    attentionSpan: vary(p.attentionSpan, 0.2),
    energy: vary(p.energy, 0.2),
    socialness: vary(p.socialness, 0.2),
    mischief: vary(p.mischief, 0.2),
    sleepiness: vary(p.sleepiness, 0.2),
  };
}
